import Foundation

// MARK: - Clipboard buddy

/// The last few things you copied, newest first. It lives only in memory: it is never written
/// to disk and is gone when Cookie quits.
struct ClipboardHistory: Equatable {
    static let capacity = 10
    /// Longer copies are kept whole, but huge ones (a whole document) are skipped.
    static let maximumLength = 20_000

    private(set) var items: [String] = []

    /// Pasteboard types that password managers and other apps use to say "don't keep this".
    /// See nspasteboard.org.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    static func isPrivate(types: [String]) -> Bool {
        types.contains { privateTypes.contains($0) }
    }

    /// Adds a copy. Blank text and very long text are ignored; copying something again moves it
    /// to the top instead of repeating it.
    @discardableResult
    mutating func add(_ text: String) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maximumLength else { return false }
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > Self.capacity { items.removeLast(items.count - Self.capacity) }
        return true
    }

    mutating func clear() { items = [] }

    /// One line for the menu: whitespace collapsed, cut to `length`.
    static func preview(_ text: String, length: Int = 48) -> String {
        let flat = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return flat.count > length ? String(flat.prefix(length - 1)) + "…" : flat
    }
}

// MARK: - File drop zone

enum FileDropAction: Equatable {
    case move(to: URL)
    case copy(to: URL)
    case zip
}

enum FileDrop {
    /// A destination name that doesn't overwrite anything: "Report.pdf", "Report 2.pdf"…
    static func destination(for source: URL, in folder: URL, existing: Set<String>) -> URL {
        folder.appendingPathComponent(ScreenshotTidy.uniqueName(source.lastPathComponent, existing: existing))
    }

    /// Where the zip goes: beside the first file. One file becomes "Name.zip", several become
    /// "Archive.zip".
    static func zipURL(for sources: [URL], existing: Set<String>) -> URL? {
        guard let first = sources.first else { return nil }
        let folder = first.deletingLastPathComponent()
        let base = sources.count == 1 ? first.deletingPathExtension().lastPathComponent : "Archive"
        return folder.appendingPathComponent(ScreenshotTidy.uniqueName("\(base).zip", existing: existing))
    }

    static func summary(count: Int, action: FileDropAction) -> String {
        let things = count == 1 ? "it" : "all \(count)"
        switch action {
        case .move(let folder): return "Filed \(things) in \(folder.lastPathComponent)!"
        case .copy(let folder): return "Copied \(things) to \(folder.lastPathComponent)!"
        case .zip: return count == 1 ? "Zipped it up!" : "Zipped all \(count) together!"
        }
    }
}

// MARK: - Ask Cookie

/// One line of the chat window.
struct ChatLine: Identifiable, Equatable {
    enum Speaker: Equatable { case you, cookie, notice }

    let id = UUID()
    let speaker: Speaker
    let text: String
}

enum AskCookie {
    /// Claude Opus 5.5, at low effort: chat is short and quick, and doesn't need deep thinking.
    static let model = "claude-opus-5-5"
    static let endpoint = URL(string: "https://api.anthropic.com/v1/messages")!
    static let apiVersion = "2026-10-21"
    /// Lets the API answer from another model when this one declines, instead of failing.
    static let fallbackBeta = "server-side-fallback-2026-07-01"
    static let maxTokens = 4096
    /// A conversation is started over after this many messages, rather than trimmed, so it is
    /// never edited after the fact.
    static let maximumMessages = 40
    static let maximumQuestion = 2000

    static func systemPrompt(name: String, personality: String) -> String {
        """
        You are \(name), a small \(personality) cat who lives on the user's Mac desktop as a companion app. \
        You chat with the person who looks after you. Stay in character as a friendly cat: warm, a little playful, \
        occasionally cat-like (a purr, a stretch, a slow blink), but still genuinely helpful when asked a real question. \
        Keep replies short: one to three sentences unless the person asks for more detail. Use plain text without \
        Markdown headings or tables, because your words appear in a small chat window. You can't see the screen, \
        files, or anything on the Mac, and you can't take actions; if asked to, say so kindly and suggest what the \
        person could do instead. Never ask for passwords or personal details.
        """
    }

    /// The Messages API request body. `messages` holds earlier turns exactly as they came back,
    /// so any thinking blocks are passed back unchanged.
    static func requestBody(system: String, messages: [[String: Any]]) -> [String: Any] {
        [
            "model": model,
            "max_tokens": maxTokens,
            "system": system,
            "messages": messages,
            "output_config": ["effort": "low"],
            "fallbacks": "default",
        ]
    }

    static func headers(apiKey: String) -> [String: String] {
        [
            "x-api-key": apiKey,
            "anthropic-version": apiVersion,
            "anthropic-beta": fallbackBeta,
            "content-type": "application/json",
        ]
    }

    enum Reply: Equatable {
        case text(String, content: [AnyEquatableJSON])
        case declined
        case failed(String)
    }

    /// Reads a Messages API response: the reply text, plus the content blocks to send back next turn.
    static func parse(data: Data, status: Int) -> Reply {
        guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
            return .failed("Cookie got a reply she couldn't read (HTTP \(status)).")
        }
        guard (200..<300).contains(status) else {
            let error = json["error"] as? [String: Any]
            let type = error?["type"] as? String ?? ""
            switch status {
            case 401: return .failed("That API key didn't work. Check it in Settings → Ask Cookie.")
            case 403: return .failed("That API key isn't allowed to use this model.")
            case 429: return .failed("Too many questions at once. Try again in a moment.")
            case 529, 500..<600: return .failed("Claude is busy right now. Try again in a moment.")
            default:
                let message = error?["message"] as? String ?? "HTTP \(status)"
                return .failed(type.isEmpty ? message : "\(type): \(message)")
            }
        }
        if json["stop_reason"] as? String == "refusal" { return .declined }
        let content = json["content"] as? [[String: Any]] ?? []
        let text = content
            .filter { $0["type"] as? String == "text" }
            .compactMap { $0["text"] as? String }
            .joined()
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return .failed("Cookie didn't have anything to say. Try asking again.") }
        return .text(text, content: content.map(AnyEquatableJSON.init))
    }
}

/// A JSON object kept exactly as received, comparable for tests.
struct AnyEquatableJSON: Equatable {
    let value: [String: Any]

    init(_ value: [String: Any]) { self.value = value }

    static func == (lhs: Self, rhs: Self) -> Bool {
        NSDictionary(dictionary: lhs.value).isEqual(to: rhs.value)
    }
}
